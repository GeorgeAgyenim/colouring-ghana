/**
 * Renders the dated benchmark result file (`docs/benchmarks/<date>-map-<before|after>.md`)
 * from the JSON run records, in the shape docs/benchmarks/map-migration-method.md v1 requires:
 * hardware, browser, connection and date per run; bytes beside every timing; targets set
 * from run B of the "before" baseline.
 *
 * Implements NFR-1.4, NFR-1.5; see ADR-0027. No Playwright dependency.
 */
import { INITIAL_LOAD_SEGMENT_ID, MetricStats, RunResult, RunStats, SegmentStats, summariseRun, METHOD_VERSION } from './results';
import { RunId } from './run-config';

const RUN_ORDER: RunId[] = ['A', 'B', 'C'];
const METHOD_FILE = 'docs/benchmarks/map-migration-method.md';
const UNKNOWN_TARGET = 'Unknown — to be confirmed when run B is recorded';

export interface ReportOptions {
    label: 'before' | 'after';
    date: string;
    /** The "before" runs, when rendering an "after" file, so the targets can be repeated with the result. */
    baseline?: RunResult[];
    /** Date of the "before" file the baseline came from. */
    baselineDate?: string;
}

export function renderReport(runs: RunResult[], options: ReportOptions): string {
    const ordered = RUN_ORDER.map(id => runs.find(r => r.run === id)).filter((r): r is RunResult => r !== undefined);
    const lines: string[] = [];
    const stackName = options.label === 'before' ? 'Leaflet + Mapnik raster tiles' : 'MapLibre GL + PMTiles archive';

    lines.push(`# Map benchmark — ${options.label} (${stackName}) — ${options.date}`);
    lines.push('');
    lines.push(`Method: \`${METHOD_FILE}\` version ${METHOD_VERSION}. Requirements: NFR-1.4, NFR-1.5. Decision: ADR-0027.`);
    lines.push('Generated by `npm run benchmark:map` in `app/` (script `app/e2e/benchmark/map-benchmark.e2e.ts`); the raw');
    lines.push(`records are the \`run-<A|B|C>.json\` files in \`docs/benchmarks/${options.date}-map-${options.label}/\`. Do not edit`);
    lines.push('this file by hand; re-run the script.');
    lines.push('');
    lines.push('Every timing is reported with the bytes transferred for the same step (method v1, "Why bytes as well');
    lines.push('as time"). Median and p95 are across the repetitions of a run. "Buildings tiles" is the layer the');
    lines.push('migration replaces (Mapnik `/tiles/` PNGs before; archive range requests and the edits-since overlay');
    lines.push('after); the OpenStreetMap basemap is identical before and after and is reported for completeness.');
    lines.push('');

    lines.push('## Runs recorded');
    lines.push('');
    for (const id of RUN_ORDER) {
        const run = ordered.find(r => r.run === id);
        lines.push(`- Run ${id}: ${run ? 'recorded' : 'not recorded'}`);
    }
    lines.push('');

    for (const run of ordered) {
        lines.push(...renderRun(run));
    }

    lines.push(...renderTargets(options, ordered));
    return lines.join('\n') + '\n';
}

function renderRun(run: RunResult): string[] {
    const s = summariseRun(run);
    const lines: string[] = [];
    lines.push(`## Run ${run.run} — ${run.runDescription}`);
    lines.push('');
    lines.push(`- Date: ${run.date} (recorded ${run.recordedAt})`);
    lines.push(`- Hardware: ${run.device}`);
    lines.push(`- Browser: ${run.browser.name} ${run.browser.version}${run.browser.headless ? ' (headless)' : ''}${run.viewport ? `, viewport ${run.viewport.width}x${run.viewport.height}` : ', device viewport'}`);
    lines.push(`- Connection: ${run.connection}`);
    lines.push(`- Throttle: ${run.throttle ? `${run.throttle.description} (latency ${run.throttle.latencyMs} ms, down ${run.throttle.downloadBytesPerSecond} B/s, up ${run.throttle.uploadBytesPerSecond} B/s)` : 'none'}`);
    lines.push(`- Server: ${run.baseUrl}; CDN or proxy in front: ${run.cdnOrProxy}`);
    lines.push(`- Stack: ${run.stack}; script commit ${run.scriptCommit}; path file \`${run.pathFile.path}\` sha256 ${run.pathFile.sha256}`);
    lines.push(`- Repetitions: ${s.repetitions}, fresh browser context each; cold-cache assertion ${s.coldCacheOk ? 'passed' : 'FAILED'}`);
    if (s.unmeasuredResponses > 0) {
        lines.push(`- ${s.unmeasuredResponses} response(s) had no byte count available (counted as 0 bytes)`);
    }
    lines.push('');
    lines.push('| Metric | Median | p95 | Bytes beside it (median) |');
    lines.push('|---|---|---|---|');
    lines.push(`| Time-to-interactive (navigation start to first map settle) | ${ms(s.timeToInteractiveMs.median)} | ${ms(s.timeToInteractiveMs.p95)} | initial load: ${bytes(initialLoadBytes(s))} |`);
    lines.push(`| Per-tile latency, buildings tiles, p95 across the path | ${ms(s.tileLatencyP95Ms.median)} | ${ms(s.tileLatencyP95Ms.p95)} | whole path, buildings tiles: ${bytes(s.bytesBuildingsTiles.median)} |`);
    lines.push(`| Bytes, whole path, buildings tiles | ${bytes(s.bytesBuildingsTiles.median)} | ${bytes(s.bytesBuildingsTiles.p95)} | — |`);
    lines.push(`| Bytes, whole path, basemap | ${bytes(s.bytesBasemap.median)} | ${bytes(s.bytesBasemap.p95)} | — |`);
    lines.push(`| Bytes, whole path, everything | ${bytes(s.bytesTotal.median)} | ${bytes(s.bytesTotal.p95)} | — |`);
    lines.push('');
    lines.push('Per segment (median across repetitions; p95 in brackets):');
    lines.push('');
    lines.push('| Segment | Duration | Buildings tiles fetched | Reused from cache | Bytes, buildings tiles | Bytes, basemap | Bytes, all |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const seg of s.segments) {
        lines.push(`| ${seg.name} | ${msPair(seg.durationMs)} | ${countPair(seg.tileCount)} | ${countPair(seg.tilesReused)} | ${bytesPair(seg.bytesBuildingsTiles)} | ${bytesPair(seg.bytesBasemap)} | ${bytesPair(seg.bytesTotal)} |`);
    }
    lines.push('');
    return lines;
}

function renderTargets(options: ReportOptions, runs: RunResult[]): string[] {
    const lines: string[] = [];
    lines.push('## Targets (set from the "before" baseline, run B)');
    lines.push('');
    lines.push('Pass rule (method v1): "after" must be less than or equal to "before" on every metric in run B.');
    lines.push('');

    const baselineRuns = options.label === 'before' ? runs : (options.baseline ?? []);
    if (options.label === 'after') {
        lines.push(`Baseline: \`docs/benchmarks/${options.baselineDate ?? 'Unknown — to be confirmed by the product owner'}-map-before.md\`.`);
        lines.push('');
    }
    const baselineB = baselineRuns.find(r => r.run === 'B');
    if (!baselineB) {
        lines.push(`- NFR-1.4 time-to-interactive target: ${UNKNOWN_TARGET}`);
        lines.push(`- Bytes target (whole path, buildings tiles): ${UNKNOWN_TARGET}`);
        lines.push('');
        return lines;
    }

    const b = summariseRun(baselineB);
    lines.push(`- NFR-1.4 time-to-interactive target: at most ${ms(b.timeToInteractiveMs.median)} (median) and ${ms(b.timeToInteractiveMs.p95)} (p95) under the run B profile, cold cache.`);
    lines.push(`- Bytes target (whole path, buildings tiles): at most ${bytes(b.bytesBuildingsTiles.median)} (median) and ${bytes(b.bytesBuildingsTiles.p95)} (p95).`);
    lines.push(`- Per-tile latency (NFR-1.5 reference): baseline p95 ${ms(b.tileLatencyP95Ms.median)} (median across repetitions); the NFR-1.5 figure of 200 ms per tile at p95 applies to the archive after the migration.`);

    if (options.label === 'after') {
        const afterB = runs.find(r => r.run === 'B');
        if (afterB) {
            const a = summariseRun(afterB);
            lines.push('');
            lines.push('| Metric (run B, median) | Before | After | Result |');
            lines.push('|---|---|---|---|');
            lines.push(`| Time-to-interactive | ${ms(b.timeToInteractiveMs.median)} | ${ms(a.timeToInteractiveMs.median)} | ${verdict(b.timeToInteractiveMs, a.timeToInteractiveMs)} |`);
            lines.push(`| Per-tile latency p95 | ${ms(b.tileLatencyP95Ms.median)} | ${ms(a.tileLatencyP95Ms.median)} | ${verdict(b.tileLatencyP95Ms, a.tileLatencyP95Ms)} |`);
            lines.push(`| Bytes, buildings tiles | ${bytes(b.bytesBuildingsTiles.median)} | ${bytes(a.bytesBuildingsTiles.median)} | ${verdict(b.bytesBuildingsTiles, a.bytesBuildingsTiles)} |`);
            lines.push(`| Bytes, everything | ${bytes(b.bytesTotal.median)} | ${bytes(a.bytesTotal.median)} | ${verdict(b.bytesTotal, a.bytesTotal)} |`);
            lines.push('');
            lines.push('Every segment (run B, median): the pass rule applies to each row.');
            lines.push('');
            lines.push('| Segment | Duration before | Duration after | Result | Bytes (buildings tiles) before | after | Result |');
            lines.push('|---|---|---|---|---|---|---|');
            for (const before of b.segments) {
                const afterSegment = a.segments.find(seg => seg.id === before.id);
                lines.push(renderSegmentVerdict(before, afterSegment));
            }
        }
    }
    lines.push('');
    return lines;
}

function renderSegmentVerdict(before: SegmentStats, after: SegmentStats | undefined): string {
    if (!after) {
        return `| ${before.name} | ${ms(before.durationMs.median)} | missing | not comparable | ${bytes(before.bytesBuildingsTiles.median)} | missing | not comparable |`;
    }
    return `| ${before.name} | ${ms(before.durationMs.median)} | ${ms(after.durationMs.median)} | ${verdict(before.durationMs, after.durationMs)} `
        + `| ${bytes(before.bytesBuildingsTiles.median)} | ${bytes(after.bytesBuildingsTiles.median)} | ${verdict(before.bytesBuildingsTiles, after.bytesBuildingsTiles)} |`;
}

function verdict(before: MetricStats, after: MetricStats): string {
    if (before.median === null || after.median === null) {
        return 'not comparable';
    }
    return after.median <= before.median ? 'pass' : 'FAIL';
}

function initialLoadBytes(s: RunStats): number | null {
    const initial = s.segments.find(seg => seg.id === INITIAL_LOAD_SEGMENT_ID);
    return initial ? initial.bytesTotal.median : null;
}

function ms(value: number | null): string {
    return value === null ? 'n/a' : `${Math.round(value)} ms`;
}

/** Exact byte counts, so a reader can recompute the comparison; thousands separated for reading. */
function bytes(value: number | null): string {
    return value === null ? 'n/a' : `${Math.round(value).toLocaleString('en-GB')} B`;
}

function msPair(stat: MetricStats): string {
    return `${ms(stat.median)} (${ms(stat.p95)})`;
}

function bytesPair(stat: MetricStats): string {
    return `${bytes(stat.median)} (${bytes(stat.p95)})`;
}

function countPair(stat: MetricStats): string {
    const fmt = (v: number | null) => (v === null ? 'n/a' : String(Math.round(v)));
    return `${fmt(stat.median)} (${fmt(stat.p95)})`;
}
